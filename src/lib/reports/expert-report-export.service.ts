export function isExportJsonRecord(
    value: unknown,
): value is ExportJsonRecord {
    return (
        value !== null &&
        typeof value === "object" &&
        !Array.isArray(value)
    );
}

function toExportJsonRecord(
    value: unknown,
) {
    const normalized =
        toCanonicalJson(value);

    return isExportJsonRecord(
        normalized,
    )
        ? normalized
        : null;
}

function toExportJsonRecordArray(
    value: unknown,
) {
    const normalized =
        toCanonicalJson(value);

    if (!Array.isArray(normalized)) {
        return [];
    }

    return normalized.filter(
        isExportJsonRecord,
    );
}

export async function loadExpertReportExportSource({
    userId,
    reportId,
    version,
}: LoadExpertReportExportOptions): Promise<ExpertReportExportSource> {
    const report =
        await prisma.expertReport.findFirst({
            where: {
                id: reportId,
                userId,
                deletedAt: null,
            },

            include: {
                client: {
                    select: {
                        id: true,
                        name: true,
                        tradeName: true,
                        documentNumber:
                            true,
                    },
                },

                legalProcess: {
                    select: {
                        id: true,
                        caseNumber: true,
                        title: true,
                        court: true,
                        courtDivision:
                            true,
                        district: true,
                        city: true,
                        state: true,
                        actionClass: true,
                        subject: true,
                    },
                },

                revisions: {
                    where: {
                        version,
                    },

                    take: 1,

                    include: {
                        sections: {
                            orderBy: {
                                position:
                                    "asc",
                            },
                        },

                        calculationLinks: {
                            orderBy: {
                                position:
                                    "asc",
                            },

                            include: {
                                calculation: {
                                    select: {
                                        id: true,
                                        type: true,
                                        title: true,
                                        description:
                                            true,
                                        currency: true,
                                    },
                                },

                                calculationRevision:
                                {
                                    include:
                                    {
                                        lines: {
                                            orderBy:
                                            {
                                                sequence:
                                                    "asc",
                                            },
                                        },
                                    },
                                },
                            },
                        },
                    },
                },
            },
        });

    if (!report) {
        throw new ExpertReportServiceError(
            "Laudo não encontrado.",
            404,
            "REPORT_NOT_FOUND",
        );
    }

    const revision =
        report.revisions[0];

    if (!revision) {
        throw new ExpertReportServiceError(
            `A revisão ${version} do laudo não foi encontrada.`,
            404,
            "REPORT_REVISION_NOT_FOUND",
        );
    }

    return {
        report: {
            id: report.id,
            title: report.title,
            reportNumber:
                report.reportNumber,
            status: report.status,
            currentVersion:
                report.currentVersion,
            purpose: report.purpose,

            referenceDate:
                report.referenceDate?.toISOString() ??
                null,

            place: report.place,

            issuedAt:
                report.issuedAt?.toISOString() ??
                null,
        },

        client: report.client,

        legalProcess:
            report.legalProcess,

        revision: {
            id: revision.id,
            version: revision.version,
            status: revision.status,
            title: revision.title,

            reportNumber:
                revision.reportNumber,

            purpose: revision.purpose,

            referenceDate:
                revision.referenceDate?.toISOString() ??
                null,

            place: revision.place,

            issuedAt:
                revision.issuedAt?.toISOString() ??
                null,

            templateVersion:
                revision.templateVersion,

            integrityHash:
                revision.integrityHash,

            notes: revision.notes,

            createdAt:
                revision.createdAt.toISOString(),

            updatedAt:
                revision.updatedAt.toISOString(),

            sourceSnapshot:
                toCanonicalJson(
                    revision.sourceSnapshot,
                ),

            clientSnapshot:
                revision.clientSnapshot ===
                    null
                    ? null
                    : toCanonicalJson(
                        revision.clientSnapshot,
                    ),

            legalProcessSnapshot:
                revision.legalProcessSnapshot ===
                    null
                    ? null
                    : toCanonicalJson(
                        revision.legalProcessSnapshot,
                    ),

            professionalSnapshot:
                revision.professionalSnapshot ===
                    null
                    ? null
                    : toCanonicalJson(
                        revision.professionalSnapshot,
                    ),

            questionsSnapshot:
                revision.questionsSnapshot ===
                    null
                    ? null
                    : toCanonicalJson(
                        revision.questionsSnapshot,
                    ),

            sourceDocumentsSnapshot:
                revision.sourceDocumentsSnapshot ===
                    null
                    ? null
                    : toCanonicalJson(
                        revision.sourceDocumentsSnapshot,
                    ),

            sections:
                revision.sections.map(
                    (section) => ({
                        id: section.id,
                        type: section.type,
                        title:
                            section.title,
                        plainText:
                            section.plainText,

                        content:
                            section.content ===
                                null
                                ? null
                                : toCanonicalJson(
                                    section.content,
                                ),

                        position:
                            section.position,

                        isVisible:
                            section.isVisible,

                        isAutoGenerated:
                            section.isAutoGenerated,
                    }),
                ),
        },

        calculations:
            revision.calculationLinks.map(
                (link) => ({
                    calculation: {
                        id:
                            link.calculation
                                .id,

                        type:
                            link.calculation
                                .type,

                        title:
                            link.calculation
                                .title,

                        description:
                            link.calculation
                                .description,

                        currency:
                            link.calculation
                                .currency,
                    },

                    revision: {
                        id:
                            link.calculationRevision
                                .id,

                        version:
                            link.calculationRevision
                                .version,

                        engineVersion:
                            link.calculationRevision
                                .engineVersion,

                        integrityHash:
                            link.calculationRevision
                                .integrityHash,

                        referenceDate:
                            link.calculationRevision
                                .referenceDate
                                ?.toISOString() ??
                            null,

                        lines:
                            link.calculationRevision
                                .lines.map(
                                    (
                                        line,
                                    ) =>
                                        toExportJsonRecord(
                                            line,
                                        ) ??
                                        {},
                                ),
                    },

                    snapshot:
                        toCanonicalJson(
                            link.snapshot,
                        ),
                }),
            ),
    };
}

export function getStringFromJson(
    value:
        | CanonicalJson
        | null,
    key: string,
) {
    if (!isExportJsonRecord(value)) {
        return null;
    }

    const item = value[key];

    if (
        typeof item === "string" ||
        typeof item === "number"
    ) {
        return String(item);
    }

    return null;
}

