export function formatExportLineValue(
    value:
        | CanonicalJson
        | undefined,
    kind: ExportLineColumnKind,
    currency: string,
) {
    if (kind === "money") {
        return formatExportMoney(
            value,
            currency,
        );
    }

    if (kind === "percent") {
        return formatExportPercent(
            value,
        );
    }

    if (kind === "date") {
        return typeof value === "string"
            ? formatExportDate(value)
            : "—";
    }

    if (kind === "number") {
        if (
            value === null ||
            value === undefined ||
            value === ""
        ) {
            return "—";
        }

        const numericValue =
            Number(value);

        return Number.isFinite(
            numericValue,
        )
            ? new Intl.NumberFormat(
                "pt-BR",
            ).format(numericValue)
            : String(value);
    }

    return formatExportPrimitive(
        value,
    );
}

export function getVisibleExportSections(
    source: ExpertReportExportSource,
) {
    return [
        ...source.revision.sections,
    ]
        .filter(
            (section) =>
                section.isVisible,
        )
        .sort(
            (left, right) =>
                left.position -
                right.position,
        );
}

export function splitExportText(
    text: string | null,
) {
    if (!text?.trim()) {
        return [
            "Nenhum conteúdo informado nesta seção.",
        ];
    }

    return text
        .replace(/\r\n/g, "\n")
        .split("\n");
}

function sanitizeFileNamePart(
    value: string,
) {
    return value
        .normalize("NFD")
        .replace(
            /[\u0300-\u036f]/g,
            "",
        )
        .toLowerCase()
        .replace(
            /[^a-z0-9]+/g,
            "-",
        )
        .replace(
            /^-+|-+$/g,
            "",
        )
        .slice(0, 100);
}

export function getExpertReportExportFileName(
    source: ExpertReportExportSource,
    extension: "pdf" | "docx",
) {
    const base =
        source.revision.reportNumber
            ? `laudo-${source.revision.reportNumber}`
            : source.revision.title;

    const safeBase =
        sanitizeFileNamePart(base) ||
        "laudo-pericial";

    return `${safeBase}-revisao-${source.revision.version}.${extension}`;
}

export async function registerExpertReportExport({
    userId,
    source,
    fileName,
    mimeType,
    buffer,
    format,
    requestMetadata,
}: RegisterExpertReportExportOptions) {
    const integrityHash =
        createHash("sha256")
            .update(buffer)
            .digest("hex");

    const calculationRevisionId =
        source.calculations[0]
            ?.revision.id ??
        null;

    return prisma.$transaction(
        async (transaction) => {
            const document =
                await transaction.generatedDocument.create(
                    {
                        data: {
                            userId,

                            expertReportId:
                                source.report.id,

                            expertReportRevisionId:
                                source.revision.id,

                            calculationRevisionId,

                            type:
                                GeneratedDocumentType.EXPERT_REPORT,

                            status:
                                GeneratedDocumentStatus.READY,

                            fileName,

                            storageKey:
                                null,

                            mimeType,

                            sizeBytes:
                                buffer.byteLength,

                            integrityHash,

                            pageCount:
                                null,

                            templateVersion:
                                source.revision
                                    .templateVersion,

                            errorMessage:
                                null,

                            generatedAt:
                                new Date(),
                        },
                    },
                );

            await transaction.auditEvent.create({
                data: {
                    userId,

                    entityType:
                        "GeneratedDocument",

                    entityId:
                        document.id,

                    action:
                        AuditAction.GENERATE_DOCUMENT,

                    description: `${format} do laudo ${source.revision.title}, revisão ${source.revision.version}, gerado.`,

                    newData: {
                        generatedDocumentId:
                            document.id,

                        reportId:
                            source.report.id,

                        reportRevisionId:
                            source.revision.id,

                        reportVersion:
                            source.revision
                                .version,

                        fileName,
                        mimeType,

                        sizeBytes:
                            buffer.byteLength,

                        integrityHash,

                        templateVersion:
                            source.revision
                                .templateVersion,

                        storagePersisted:
                            false,
                    },

                    ipAddress:
                        requestMetadata?.ipAddress ??
                        null,

                    userAgent:
                        requestMetadata?.userAgent ??
                        null,
                },
            });

            await transaction.auditEvent.create({
                data: {
                    userId,

                    entityType:
                        "GeneratedDocument",

                    entityId:
                        document.id,

                    action:
                        AuditAction.DOWNLOAD_DOCUMENT,

                    description: `${format} do laudo ${source.revision.title}, revisão ${source.revision.version}, disponibilizado para download.`,

                    newData: {
                        generatedDocumentId:
                            document.id,

                        reportId:
                            source.report.id,

                        reportRevisionId:
                            source.revision.id,

                        reportVersion:
                            source.revision
                                .version,

                        fileName,
                        mimeType,
                    },

                    ipAddress:
                        requestMetadata?.ipAddress ??
                        null,

                    userAgent:
                        requestMetadata?.userAgent ??
                        null,
                },
            });

            return document;
        },
    );
}