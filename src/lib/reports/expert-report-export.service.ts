export function getProfessionalCrc(
    source: ExpertReportExportSource,
) {
    const number =
        getStringFromJson(
            source.revision
                .professionalSnapshot,
            "crcNumber",
        );

    const state =
        getStringFromJson(
            source.revision
                .professionalSnapshot,
            "crcState",
        );

    if (!number) {
        return "CRC não informado";
    }

    return `CRC${state
            ? `/${state}`
            : ""
        } ${number}`;
}

export function formatExportDate(
    value: string | null,
) {
    if (!value) {
        return "Não informada";
    }

    const date = new Date(value);

    if (
        Number.isNaN(date.getTime())
    ) {
        return value;
    }

    return new Intl.DateTimeFormat(
        "pt-BR",
    ).format(date);
}

export function formatExportDateTime(
    value: string | null,
) {
    if (!value) {
        return "Não informado";
    }

    const date = new Date(value);

    if (
        Number.isNaN(date.getTime())
    ) {
        return value;
    }

    return new Intl.DateTimeFormat(
        "pt-BR",
        {
            dateStyle: "short",
            timeStyle: "short",
        },
    ).format(date);
}

export function formatExportMoney(
    value:
        | CanonicalJson
        | undefined,
    currency: string,
) {
    if (
        value === null ||
        value === undefined ||
        value === ""
    ) {
        return "—";
    }

    const numericValue =
        Number(value);

    if (
        !Number.isFinite(
            numericValue,
        )
    ) {
        return String(value);
    }

    return new Intl.NumberFormat(
        "pt-BR",
        {
            style: "currency",
            currency,
        },
    ).format(numericValue);
}

export function formatExportPercent(
    value:
        | CanonicalJson
        | undefined,
) {
    if (
        value === null ||
        value === undefined ||
        value === ""
    ) {
        return "—";
    }

    const numericValue =
        Number(value);

    if (
        !Number.isFinite(
            numericValue,
        )
    ) {
        return String(value);
    }

    const percentage =
        Math.abs(numericValue) <= 1
            ? numericValue * 100
            : numericValue;

    return `${new Intl.NumberFormat(
        "pt-BR",
        {
            minimumFractionDigits: 2,
            maximumFractionDigits: 6,
        },
    ).format(percentage)}%`;
}

export function formatExportPrimitive(
    value:
        | CanonicalJson
        | undefined,
) {
    if (
        value === null ||
        value === undefined ||
        value === ""
    ) {
        return "—";
    }

    if (typeof value === "boolean") {
        return value
            ? "Sim"
            : "Não";
    }

    if (
        typeof value === "object"
    ) {
        return JSON.stringify(value);
    }

    return String(value);
}

function getMetadataValue(
    line: ExportJsonRecord,
    key: string,
) {
    const metadata =
        line.metadata;

    if (!isExportJsonRecord(metadata)) {
        return undefined;
    }

    return metadata[key];
}

function hasExportValue(
    value:
        | CanonicalJson
        | undefined,
) {
    return (
        value !== undefined &&
        value !== null &&
        value !== ""
    );
}

function normalizeCalculationType(
    type: string,
) {
    return type
        .trim()
        .toUpperCase()
        .replace(/[\s-]+/g, "_");
}

export function getExportCalculationLines(
    source: ExpertReportExportSource,
) {
    const calculationsSection =
        source.revision.sections.find(
            (section) =>
                section.type ===
                "CALCULATIONS",
        );

    if (
        calculationsSection &&
        isExportJsonRecord(
            calculationsSection.content,
        )
    ) {
        const sectionLines =
            calculationsSection.content
                .lines;

        const parsedLines =
            toExportJsonRecordArray(
                sectionLines,
            );

        if (parsedLines.length > 0) {
            return parsedLines;
        }
    }

    return source.calculations.flatMap(
        (calculation) =>
            calculation.revision.lines,
    );
}

