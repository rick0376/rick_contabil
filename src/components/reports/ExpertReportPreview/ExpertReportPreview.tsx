function normalizeType(type: string) {
    return type
        .trim()
        .toUpperCase()
        .replace(/[\s-]+/g, "_");
}

function isJsonRecord(
    value: unknown,
): value is Record<string, JsonValue> {
    return (
        value !== null &&
        typeof value === "object" &&
        !Array.isArray(value)
    );
}

function hasValue(
    value: JsonValue | undefined,
) {
    return (
        value !== undefined &&
        value !== null &&
        value !== ""
    );
}

function formatDate(
    value:
        | string
        | null
        | undefined,
) {
    if (!value) {
        return "Não informada";
    }

    const date = new Date(value);

    if (
        Number.isNaN(date.getTime())
    ) {
        return value;
    }

    return new Intl.DateTimeFormat(
        "pt-BR",
    ).format(date);
}

function formatDateTime(
    value:
        | string
        | null
        | undefined,
) {
    if (!value) {
        return "Não informado";
    }

    const date = new Date(value);

    if (
        Number.isNaN(date.getTime())
    ) {
        return value;
    }

    return new Intl.DateTimeFormat(
        "pt-BR",
        {
            dateStyle: "short",
            timeStyle: "short",
        },
    ).format(date);
}

function formatMoney(
    value: JsonValue | undefined,
    currency: string,
) {
    if (!hasValue(value)) {
        return "—";
    }

    const numericValue =
        Number(value);

    if (
        !Number.isFinite(
            numericValue,
        )
    ) {
        return String(value);
    }

    return new Intl.NumberFormat(
        "pt-BR",
        {
            style: "currency",
            currency,
        },
    ).format(numericValue);
}

function formatPercent(
    value: JsonValue | undefined,
) {
    if (!hasValue(value)) {
        return "—";
    }

    const numericValue =
        Number(value);

    if (
        !Number.isFinite(
            numericValue,
        )
    ) {
        return String(value);
    }

    const percentage =
        Math.abs(numericValue) <= 1
            ? numericValue * 100
            : numericValue;

    return `${new Intl.NumberFormat(
        "pt-BR",
        {
            minimumFractionDigits: 2,
            maximumFractionDigits: 6,
        },
    ).format(percentage)}%`;
}

function formatPrimitive(
    value: JsonValue | undefined,
) {
    if (!hasValue(value)) {
        return "—";
    }

    if (typeof value === "boolean") {
        return value
            ? "Sim"
            : "Não";
    }

    if (
        typeof value === "object"
    ) {
        return JSON.stringify(value);
    }

    return String(value);
}

function formatColumnValue(
    value: JsonValue | undefined,
    kind: ColumnKind,
    currency: string,
) {
    if (kind === "money") {
        return formatMoney(
            value,
            currency,
        );
    }

    if (kind === "percent") {
        return formatPercent(value);
    }

    if (kind === "date") {
        return typeof value === "string"
            ? formatDate(value)
            : "—";
    }

    if (kind === "number") {
        if (!hasValue(value)) {
            return "—";
        }

        const numericValue =
            Number(value);

        return Number.isFinite(
            numericValue,
        )
            ? new Intl.NumberFormat(
                "pt-BR",
            ).format(numericValue)
            : String(value);
    }

    return formatPrimitive(value);
}

function getMetadataValue(
    line: CalculationLineRecord,
    key: string,
) {
    const metadata =
        line.metadata;

    if (!isJsonRecord(metadata)) {
        return undefined;
    }

    return metadata[key];
}

function getCalculationLines(
    revision: ReportRevision,
    calculationsSection:
        | ReportSection
        | undefined,
) {
    if (
        calculationsSection &&
        isJsonRecord(
            calculationsSection.content,
        )
    ) {
        const storedLines =
            calculationsSection.content
                .lines;

        if (Array.isArray(storedLines)) {
            const parsedLines =
                storedLines.filter(
                    isJsonRecord,
                );

            if (
                parsedLines.length > 0
            ) {
                return parsedLines;
            }
        }
    }

    return revision.calculationLinks.flatMap(
        (link) =>
            link.calculationRevision
                .lines ?? [],
    );
}

