        calculationLink?.calculation
            .currency ?? "BRL";

    const calculationsSection =
        bodySections.find(
            (section) =>
                section.type ===
                "CALCULATIONS",
        );

    const calculationLines =
        getCalculationLines(
            selectedRevision,
            calculationsSection,
        );

    const lineColumns =
        getLineColumns(
            calculationType,
            calculationLines,
        );

    const showDraftWatermark =
        report.status !==
        "FINALIZED" ||
        selectedRevision.status !==
        "FINALIZED";

    const encodedReportId =
        encodeURIComponent(report.id);

    const selectedRevisionVersion =
        selectedRevision.version;

    function handlePrint() {
        window.print();
    }

    async function handleExport(
        format: ExportFormat,
    ) {
        setExportingFormat(format);
        setExportError("");
        setExportSuccess("");

        const extension =
            format === "PDF"
                ? "pdf"
                : "docx";

        const fallbackFileName =
            `laudo-pericial-revisao-${selectedRevisionVersion}.${extension}`;

        try {
            const response =
                await fetch(
                    `/api/reports/${encodedReportId}/revisions/${selectedRevisionVersion}/export/${extension}`,
                    {
                        method: "GET",
                        cache: "no-store",
                    },
                );

            if (!response.ok) {
                const message =
                    await getExportErrorMessage(
                        response,
                        format === "PDF"
                            ? "Não foi possível gerar o arquivo PDF."
                            : "Não foi possível gerar o arquivo Word.",
                    );

                throw new Error(message);
            }

            const blob =
                await response.blob();

            if (blob.size === 0) {
                throw new Error(
                    "O arquivo gerado está vazio.",
                );
            }

            const fileName =
                getFileNameFromHeader(
                    response.headers.get(
                        "content-disposition",
                    ),
                    fallbackFileName,
                );

            const objectUrl =
                URL.createObjectURL(blob);

            const anchor =
                document.createElement(
                    "a",
                );

            anchor.href = objectUrl;
            anchor.download = fileName;
            anchor.style.display =
                "none";

            document.body.appendChild(
                anchor,
            );

            anchor.click();
            anchor.remove();

            window.setTimeout(() => {
                URL.revokeObjectURL(
                    objectUrl,
                );
            }, 1000);

            setExportSuccess(
                format === "PDF"
                    ? "Arquivo PDF gerado e enviado para download."
                    : "Arquivo Word gerado e enviado para download.",
            );
        } catch (error) {
            setExportError(
                error instanceof Error
                    ? error.message
                    : "Não foi possível exportar o laudo.",
            );
        } finally {
            setExportingFormat(null);
        }
    }

